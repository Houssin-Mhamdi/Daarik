const enPath = "C:/Users/dell2/darna/src/lib/i18n/en.ts";
let text = fs.readFileSync(enPath, "utf8");
// insert before final closing of object: find last "};"
const idx = text.lastIndexOf("};");
if (idx === -1) throw new Error("no closing");
const before = text.slice(0, idx);
const after = text.slice(idx);
// ensure trailing comma/newline
let insert = "";
for (const [k, v] of Object.entries(mapping)) {
  // skip if already defined
  if (new RegExp("^\\s{2}" + k + ":", "m").test(text)) continue;
  insert += `  ${k}: ${JSON.stringify(v)},\n`;
}
text = before + insert + after;
fs.writeFileSync(enPath, text);
